/**
 * The same escaping the visitor renderer applies: '<' becomes its unicode
 * escape so a closing script tag inside student-authored text can never
 * terminate the JSON block, and the line/paragraph separators stay inert.
 */
export function serializePreviewPayload(payload: unknown): string {
  return JSON.stringify(payload)
    .replace(/</g, "\\u003c")
    .split(String.fromCharCode(0x2028)).join("\\u2028")
    .split(String.fromCharCode(0x2029)).join("\\u2029");
}

const DTO_SCRIPT_TAG = (safeJson: string) =>
  `<script type="application/json" id="__ONEVUE_DTO__">${safeJson}</script>`;

/** The marker an adapted artifact must carry for student data to reach it. */
const DTO_MARKER = "__ONEVUE_DTO__";

const PLACEHOLDER_COMMENT_REGEX =
  /<!--\s*<script\s+type=["']application\/json["']\s+id=["']__ONEVUE_DTO__["']>[\s\S]*?<\/script>\s*-->/i;
const ACTIVE_SCRIPT_REGEX =
  /<script\s+type=["']application\/json["']\s+id=["']__ONEVUE_DTO__["']>[\s\S]*?<\/script>/i;

/**
 * Injects the preview payload using exactly the three insertion strategies the
 * visitor renderer uses, so a template that previews correctly also renders
 * correctly for a student.
 */
export function injectPreviewDtoIntoHtml(rawHtml: string, payload: unknown): string {
  if (typeof rawHtml !== "string" || !rawHtml.trim()) {
    throw new Error("Preview injection error: entrypoint HTML is empty.");
  }
  const scriptTag = DTO_SCRIPT_TAG(serializePreviewPayload(payload));

  let html = rawHtml;
  if (PLACEHOLDER_COMMENT_REGEX.test(html)) {
    html = html.replace(PLACEHOLDER_COMMENT_REGEX, scriptTag);
  } else if (ACTIVE_SCRIPT_REGEX.test(html)) {
    html = html.replace(ACTIVE_SCRIPT_REGEX, scriptTag);
  } else if (html.includes("</head>")) {
    html = html.replace("</head>", `  ${scriptTag}\n  </head>`);
  } else {
    html = `${scriptTag}\n${html}`;
  }

  const occurrences = (html.match(/id=["']__ONEVUE_DTO__["']/g) || []).length;
  if (occurrences > 1) {
    throw new Error(`Preview injection integrity error: ${occurrences} __ONEVUE_DTO__ blocks found.`);
  }
  return html;
}

/**
 * Rewrites the release base path so the previewed document resolves its assets
 * through the artifact delivery API on the origin serving the preview. Without
 * this, an adapted artifact's absolute `/templates/<id>/<version>/...` URLs
 * point at a host that does not serve them and the preview renders blank.
 */
export function rewriteAssetBasePaths(
  html: string,
  options: { templateId: string; templateVersion: string; origin: string }
): { html: string; rewritten: number } {
  const { templateId, templateVersion, origin } = options;
  const releasePrefix = `/templates/${templateId}/${templateVersion}/`;
  const deliveryPrefix = `${origin}${TEMPLATE_ARTIFACT_API_PREFIX}/${templateId}/${templateVersion}/`;

  // Every occurrence is rewritten, not just attribute values: attribute URLs,
  // the entry document's own references and webpack's baked `publicPath`
  // literal all resolve through the same prefix, and lazy chunks depend on it.
  const parts = html.split(releasePrefix);
  return {
    html: parts.join(deliveryPrefix),
    rewritten: parts.length - 1,
  };
}

/**
 * Built-in releases (magicui-portfolio) ship as React components inside the
 * portfolio app, not as an artifact directory the delivery boundary can read.
 * They are previewable through the student's own draft preview, never here.
 */
export function isBuiltInRegistryRelease(templateId: string, templateVersion: string): boolean {
  try {
    const builtIn = (listApprovedTemplates() || []).find((t: any) => t.id === templateId);
    return Boolean(builtIn?.releases?.some((r: any) => r.version === templateVersion));
  } catch {
    return false;
  }
}

/**
 * The complete preview document, built through the artifact delivery boundary.
 *
 * Both the administrator preview and the student preview call this, so there
 * is exactly one rendering contract in the product. It is read-only: it never
 * writes storage, never changes lifecycle state and never publishes.
 *
 * `websiteMeta` lets a caller preview with its own payload (a student's draft)
 * instead of the representative sample; omitting it is what makes a preview
 * safe to hand to somebody who is not yet the profile owner.
 */
export async function renderTemplatePreviewDocument(options: {
  templateId: string;
  templateVersion: string;
  origin: string;
  websiteMeta?: Record<string, unknown>;
  storageAdapter?: unknown;
}): Promise<
  | { ok: true; html: string; manifestSha256: string; entrypoint: string; assetsRebased: number }
  | { ok: false; status: number; code: string; message: string }
> {
  const { templateId, templateVersion, origin } = options;

  const release = await resolveValidatedRelease(templateId, templateVersion, {
    storageAdapter: options.storageAdapter,
  } as never);
  if (!release.ok) {
    if (
      (release.failure === "MISSING_ARTIFACT" || release.failure === "MISSING_MANIFEST") &&
      isBuiltInRegistryRelease(templateId, templateVersion)
    ) {
      return {
        ok: false,
        status: 409,
        code: "PREVIEW_NOT_ARTIFACT_BACKED",
        message: `'${templateId}@${templateVersion}' is a built-in OneVue template. It has no stored artifact to render, so it is previewed with your own profile data instead of sample data.`,
      };
    }
    if (release.failure === "MISSING_ARTIFACT") {
      // A submission that has not been built yet has no artifact at all. The
      // artifact preview is not the place to judge it: the retained source
      // snapshot is.
      return {
        ok: false,
        status: 404,
        code: "MISSING_ARTIFACT",
        message: `No built artifact exists for '${templateId}@${templateVersion}'. The artifact preview is only available after a successful build and storage of the release; inspect the retained source snapshot instead.`,
      };
    }
    return { ok: false, status: release.httpStatus, code: release.failure, message: release.error };
  }

  const entrypoint = release.manifest.entrypoint || "index.html";
  const delivery = await deliverTemplateAsset(
    { templateId, templateVersion, relativePath: entrypoint },
    { storageAdapter: options.storageAdapter } as never
  );
  if (!delivery.ok) {
    return { ok: false, status: delivery.httpStatus, code: delivery.failure, message: delivery.error };
  }

  const rawHtml = (await readDeliveredAsset(delivery)).toString("utf8");

  // An artifact with no DTO contract was never adapted. Injecting the payload
  // anyway would render the template author's own demo content — and run the
  // author's third-party tags — as if it were the student's portfolio, which is
  // exactly the confusion a preview exists to prevent.
  if (!rawHtml.includes(DTO_MARKER)) {
    return {
      ok: false,
      status: 409,
      code: "ARTIFACT_NOT_DTO_ADAPTED",
      message: `'${templateId}@${templateVersion}' has no __ONEVUE_DTO__ block in its entrypoint, so this artifact was never adapted to render student data. Previewing it would show the template author's demo content instead.`,
    };
  }

  const payload = {
    dto: buildRepresentativeDto(templateId, templateVersion),
    website: {
      username: "preview",
      templateId,
      templateVersion,
      route: "/",
      preview: true,
      ...(options.websiteMeta || {}),
    },
  };

  const injected = injectPreviewDtoIntoHtml(rawHtml, payload);
  const rebased = rewriteAssetBasePaths(injected, { templateId, templateVersion, origin });

  return {
    ok: true,
    html: rebased.html,
    manifestSha256: release.manifest.manifestSha256,
    entrypoint,
    assetsRebased: rebased.rewritten,
  };
}
