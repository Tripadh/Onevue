/**
 * =========================================================================
 * OneVue Phase 8 — Administrator Template Preview
 * =========================================================================
 *
 * The preview an admin needs before approving is the document a student would
 * receive, not the raw bytes in storage. That requires two things the stored
 * artifact does not have on its own:
 *
 *   1. the injected `__ONEVUE_DTO__` payload, and
 *   2. asset URLs that resolve from wherever the preview is displayed.
 *
 * This module produces that document from bytes that already passed the
 * artifact delivery boundary and nothing else: it never writes, never changes
 * eligibility, and never touches lifecycle state.
 *
 * The DTO is synthetic sample data. A preview must not become a way to read a
 * real student's unpublished profile.
 */

import { PUBLIC_PROFILE_SCHEMA_VERSION, PublicProfileDTO_v1 } from "./public-profile-dto";
import {
  deliverTemplateAsset,
  readDeliveredAsset,
  resolveValidatedRelease,
} from "./template-artifact-delivery";

export const TEMPLATE_ARTIFACT_API_PREFIX = "/api/public/template-artifact";

// The static registry is the source of truth for built-in releases, which are
// bundled into the portfolio app instead of stored as versioned artifacts.
const { listApprovedTemplates } = require("./template-registry");

